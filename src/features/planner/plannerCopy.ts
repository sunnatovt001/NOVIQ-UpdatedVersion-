type RoadmapPhase = {
  phase: string;
  title: string;
  status: string;
  state: "done" | "current" | "locked";
  weeks: string[];
};

const firstNumber = (value: string) => Number(value.match(/\d+/)?.[0] || 1);

export const localizeRoadmapPhases = (
  phases: RoadmapPhase[],
  weakestName: string,
  locale: AppLocale,
) => {
  if (locale === "en") return phases;
  const copy = getPlannerCopy(locale);
  const area = localizePlannerSection(weakestName, locale);
  return phases.map((phase, index) => {
    const duration = firstNumber(phase.weeks[0]);
    const titles = [copy.phaseOneTitle, copy.phaseTwoTitle, copy.phaseThreeTitle];
    const weeks = index === 0
      ? [formatPlannerText(copy.weeksRange, { count: duration }), copy.baselineCheck, formatPlannerText(copy.foundations, { area }), copy.mistakeLog]
      : index === 1
        ? [formatPlannerText(copy.nextWeeks, { count: duration }), formatPlannerText(copy.intensivePractice, { area }), copy.timedBlocks, copy.weeklyRecalculation]
        : [formatPlannerText(copy.finalWeeks, { count: duration }), copy.mockCycles, copy.weaknessCleanup, copy.scoreStabilization];
    return {
      ...phase,
      phase: `${copy.phase} ${index + 1}`,
      title: titles[index],
      status: phase.state === "done" ? copy.completed : phase.state === "current" ? copy.currentPhase : copy.locked,
      weeks,
    };
  });
};
