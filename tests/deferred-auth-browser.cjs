const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const context=await browser.newContext({viewport:{width:320,height:740}});
    const page=await context.newPage();
    let release, requested=false;
    const held=new Promise(resolve=>{release=resolve;});
    await page.route('**/src/features/auth/AuthDialog.tsx*',async route=>{requested=true;await held;await route.continue();});
    await page.goto('http://127.0.0.1:4180/');
    const signup=page.locator('.nl-hero .nl-primary');await signup.waitFor();
    assert.equal(requested,false);
    await signup.click();await page.locator('#auth-loading-title').waitFor();
    await page.waitForFunction(()=>document.activeElement?.closest('[role="dialog"]'));
    const pending=page.getByRole('dialog');
    assert.equal(await page.locator('#root').evaluate(root=>root.inert),true);
    for(const key of ['Tab','Shift+Tab']){await page.keyboard.press(key);assert.equal(await pending.evaluate(panel=>panel.contains(document.activeElement)),true);}
    await page.keyboard.press('Escape');await pending.waitFor({state:'detached'});
    assert.equal(await page.locator('#root').evaluate(root=>root.inert),false);
    assert.equal(await signup.evaluate(button=>button===document.activeElement),true);
    release();
    await page.waitForTimeout(300);
    assert.equal(await page.getByRole('dialog').count(),0);
    await signup.click();
    const form=page.getByRole('dialog',{name:'Create your study account',exact:true});await form.waitFor();
    await page.keyboard.press('Escape');await form.waitFor({state:'detached'});
    assert.equal(await signup.evaluate(button=>button===document.activeElement),true);
    await context.close();
    console.log('PASS auth module is deferred; pending focus/Escape, inert restore, cancelled late import and loaded form focus restore');
    const failedContext=await browser.newContext({viewport:{width:320,height:740}});
    const failedPage=await failedContext.newPage();
    await failedPage.route('**/src/features/auth/AuthDialog.tsx*',route=>route.fulfill({status:503,body:'Unavailable'}));
    await failedPage.goto('http://127.0.0.1:4180/');
    const opener=failedPage.locator('.nl-hero .nl-primary');await opener.click();
    await failedPage.getByRole('alert').waitFor();
    const errorDialog=failedPage.getByRole('dialog');
    await failedPage.keyboard.press('Shift+Tab');assert.equal(await errorDialog.evaluate(panel=>panel.contains(document.activeElement)),true);
    await errorDialog.getByRole('button',{name:'Close auth form',exact:true}).click();await errorDialog.waitFor({state:'detached'});
    assert.equal(await opener.evaluate(button=>button===document.activeElement),true);
    assert.equal(await failedPage.locator('#root').evaluate(root=>root.inert),false);
    assert.equal(await failedPage.evaluate(()=>document.body.style.overflow),'');
    await failedContext.close();
    console.log('PASS import failure is cancellable, keyboard contained and restores focus/scroll');
    const timeoutContext=await browser.newContext({viewport:{width:320,height:740}});
    const timeoutPage=await timeoutContext.newPage();
    let resume;
    const delayed=new Promise(resolve=>{resume=resolve;});
    await timeoutPage.route('**/src/features/auth/AuthDialog.tsx*',async route=>{await delayed;await route.continue();});
    await timeoutPage.goto('http://127.0.0.1:4180/');
    const timeoutOpener=timeoutPage.locator('.nl-hero .nl-primary');
    await timeoutOpener.click();
    await timeoutPage.getByRole('alert').waitFor({timeout:22000});
    const timeoutDialog=timeoutPage.getByRole('dialog');
    await timeoutDialog.getByRole('button',{name:'Retry page',exact:true}).click();
    await timeoutPage.getByRole('heading',{name:'Loading page…',exact:true}).waitFor();
    resume();
    const restored=timeoutPage.getByRole('dialog',{name:'Create your study account',exact:true});
    await restored.waitFor();
    await timeoutPage.keyboard.press('Escape');await restored.waitFor({state:'detached'});
    assert.equal(await timeoutOpener.evaluate(button=>button===document.activeElement),true);
    assert.equal(await timeoutPage.locator('#root').evaluate(root=>root.inert),false);
    assert.equal(await timeoutPage.evaluate(()=>document.body.style.overflow),'');
    await timeoutContext.close();
    console.log('PASS real 15s import deadline settles and retry opens the form after network resumes');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
